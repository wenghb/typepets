#!/usr/bin/env python3
"""Draw the homepage's world map of where TypePets visitors come from.

The map is a grid of grey dots, one per patch of land, with a bubble on every
country that sent at least one visitor through Google Search. A bubble's area
follows the country's share of visits; the page shows no numbers. Everything is
written as static HTML between the visitor-map markers in index.html, so the
homepage loads no map library and makes no requests for it.

To refresh it, export the data from Search Console (Performance, any date range,
EXPORT, Download CSV) and pass the zip it downloads:

    python3 scripts/visitor-map/build.py ~/Downloads/typepets.com-Performance-on-Search-2026-10-19.zip
    python3 scripts/visitor-map/build.py export.zip --check   # exit 1 if index.html is out of date

The zip's Countries.csv gives the clicks per country and Chart.csv the dates.
A country name the script can't place stops the build with a list of the names, so
nobody quietly drops off the map; add those to NAME_FIXES below.

The land dots and each country's names and label point (where its bubble goes)
live in land.json next to this script. It only needs rebuilding to change the grid,
from Natural Earth's 1:50m countries (public domain; needs numpy):

    python3 scripts/visitor-map/build.py --land ne_50m_admin_0_countries.geojson
    # https://github.com/nvkelso/natural-earth-vector/blob/master/geojson/ne_50m_admin_0_countries.geojson
"""
import argparse
import csv
import datetime
import html
import io
import json
import math
import pathlib
import re
import sys
import unicodedata
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
LAND_FILE = pathlib.Path(__file__).resolve().parent / 'land.json'
INDEX = ROOT / 'index.html'
START = '<!-- visitor-map:start (generated by scripts/visitor-map/build.py; edit the script, not this block) -->'
END = '<!-- visitor-map:end -->'

# The grid: COLS dots across the world on a Miller projection, from 83°N (northern
# Greenland) to 56°S (Cape Horn). Antarctica is left off.
COLS = 160
LAT_TOP, LAT_BOTTOM = 83.0, -56.0

# Bubble radius in dots: the most-visited country gets BUBBLE_MAX and the rest scale by
# area (radius ~ square root of visits), never smaller than BUBBLE_MIN.
BUBBLE_MAX, BUBBLE_MIN = 7.0, 0.9
LABELS = 6     # countries named on the map (desktop only; phones get the list below it)
PINGS = 5      # pulsing rings on the countries with the most visits
TOP_CHIPS = 8  # countries in the "Most visits from" list
LABEL_SIZE = 2.3  # map label font size, in dots

# Search Console's country names that don't match a Natural Earth name.
NAME_FIXES = {
    'congo kinshasa': 'COD',
    'congo brazzaville': 'COG',
    'us virgin islands': 'VIR',
    'british virgin islands': 'VGB',
    'macau': 'MAC',
    'macedonia': 'MKD',
    'cote divoire': 'CIV',
    'turkiye': 'TUR',
    'caribbean netherlands': 'NLD',
    'st lucia': 'LCA',
    'st kitts and nevis': 'KNA',
    'st vincent and grenadines': 'VCT',
    'st pierre and miquelon': 'SPM',
    'st martin': 'MAF',
    'st barthelemy': 'BLM',
    'st helena': 'SHN',
    'sao tome and principe': 'STP',
    'falkland islands islas malvinas': 'FLK',
    'micronesia': 'FSM',
    'vatican city': 'VAT',
    'eswatini': 'SWZ',
    'cape verde': 'CPV',
    'timor leste': 'TLS',
    'gambia': 'GMB',
    'bahamas': 'BHS',
    'palestine': 'PSX',
    'reunion': 'FRA',
    'martinique': 'FRA',
    'guadeloupe': 'FRA',
    'french guiana': 'FRA',
    'mayotte': 'FRA',
}
# Search Console rows that aren't a place.
NOT_PLACES = {'unknown region'}
# Names shown on the page come from Search Console, except these.
SHOWN_AS = {'Congo - Kinshasa': 'DR Congo', 'Congo - Brazzaville': 'Congo', 'Myanmar (Burma)': 'Myanmar'}


def norm(name):
    """'Bosnia & Herzegovina' -> 'bosnia and herzegovina', 'Côte d’Ivoire' -> 'cote divoire'."""
    name = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    name = name.lower().replace('&', ' and ')
    name = re.sub(r"[.'’]", '', name)
    name = re.sub(r'[^a-z0-9]+', ' ', name)
    return name.strip()


# ── Projection ───────────────────────────────────────────────────────────────

def miller_y(lat):
    return 1.25 * math.log(math.tan(math.pi / 4 + 0.4 * math.radians(lat)))


def miller_lat(y):
    return math.degrees(2.5 * math.atan(math.exp(0.8 * y)) - 0.625 * math.pi)


STEP = 2 * math.pi / COLS
Y_TOP = miller_y(LAT_TOP)
ROWS = math.ceil((Y_TOP - miller_y(LAT_BOTTOM)) / STEP)


def dot_x(row, col):
    """Odd rows sit half a dot to the right, so the dots pack like a honeycomb."""
    return col + 0.5 * (row % 2)


def lonlat_to_xy(lon, lat):
    return (lon + 180) / 360 * COLS - 0.5, (Y_TOP - miller_y(lat)) / STEP - 0.5


# ── land.json: the land dots, and where each country's bubble goes ───────────

def build_land(geojson_path):
    import numpy as np

    rows, cols, lons, lats = [], [], [], []
    for r in range(ROWS):
        lat = miller_lat(Y_TOP - (r + 0.5) * STEP)
        for c in range(COLS):
            lon = -180 + (dot_x(r, c) + 0.5) * 360 / COLS
            if lon < 180:
                rows.append(r)
                cols.append(c)
                lons.append(lon)
                lats.append(lat)
    lons, lats = np.array(lons), np.array(lats)
    is_land = np.zeros(len(lons), dtype=bool)

    features = json.loads(pathlib.Path(geojson_path).read_text(encoding='utf-8'))['features']
    countries = []
    for feature in features:
        p = feature['properties']
        geometry = feature['geometry']
        polygons = geometry['coordinates'] if geometry['type'] == 'MultiPolygon' else [geometry['coordinates']]
        for polygon in polygons:
            outer = np.array(polygon[0])
            box = ((lons >= outer[:, 0].min()) & (lons <= outer[:, 0].max())
                   & (lats >= outer[:, 1].min()) & (lats <= outer[:, 1].max()) & ~is_land)
            idx = np.nonzero(box)[0]
            if not len(idx):
                continue
            px, py = lons[idx][:, None], lats[idx][:, None]
            inside = np.zeros(len(idx), dtype=bool)
            for ring in polygon:  # even-odd over the outline and its holes
                ring = np.array(ring)
                x1, y1 = ring[:-1, 0][None, :], ring[:-1, 1][None, :]
                x2, y2 = ring[1:, 0][None, :], ring[1:, 1][None, :]
                with np.errstate(divide='ignore', invalid='ignore'):
                    cross = ((y1 > py) != (y2 > py)) & (px < (x2 - x1) * (py - y1) / (y2 - y1) + x1)
                inside ^= (cross.sum(axis=1) % 2).astype(bool)
            is_land[idx[inside]] = True

        names = {norm(p[k]) for k in ('NAME', 'NAME_LONG', 'ADMIN', 'NAME_EN', 'NAME_SORT',
                                       'NAME_ALT', 'FORMAL_EN', 'GEOUNIT', 'SUBUNIT', 'BRK_NAME',
                                       'NAME_CIAWF') if p.get(k)}
        countries.append({
            'code': p['ADM0_A3'],
            'name': p['NAME_EN'] or p['NAME'],
            'names': sorted(names),
            'continent': p['CONTINENT'],
            'label': [round(p['LABEL_X'], 3), round(p['LABEL_Y'], 3)],
        })

    land = {
        'source': 'Natural Earth 1:50m admin-0 countries (public domain)',
        'cols': COLS, 'rows': ROWS, 'lat_top': LAT_TOP, 'lat_bottom': LAT_BOTTOM,
        'land': to_runs((rows[k], cols[k]) for k in np.nonzero(is_land)[0]),
        'countries': countries,
    }
    LAND_FILE.write_text(json.dumps(land, ensure_ascii=False, separators=(',', ':')) + '\n', encoding='utf-8')
    print(f'Wrote {LAND_FILE.relative_to(ROOT)}: {int(is_land.sum())} land dots, {len(countries)} countries')


def to_runs(dots):
    """[(row, col), ...] -> [[row, first col, length], ...] for each unbroken stretch of a row."""
    runs = []
    for row, col in sorted(dots):
        if runs and runs[-1][0] == row and runs[-1][1] + runs[-1][2] == col:
            runs[-1][2] += 1
        else:
            runs.append([row, col, 1])
    return runs


def from_runs(runs):
    return {(row, col + k) for row, col, n in runs for k in range(n)}


# ── The map ──────────────────────────────────────────────────────────────────

def read_export(path):
    """Clicks per country and the date range, from a Search Console export zip (or its folder)."""
    path = pathlib.Path(path).expanduser()

    def read(name):
        if path.is_dir():
            return (path / name).read_text(encoding='utf-8-sig')
        with zipfile.ZipFile(path) as archive:
            return archive.read(name).decode('utf-8-sig')

    clicks = {}
    for row in csv.DictReader(io.StringIO(read('Countries.csv'))):
        clicks[row['Country']] = clicks.get(row['Country'], 0) + int(row['Clicks'].replace(',', ''))

    days = [row['Date'] for row in csv.DictReader(io.StringIO(read('Chart.csv')))
            if int(row['Clicks'].replace(',', '')) or int(row['Impressions'].replace(',', ''))]
    if not days:
        sys.exit('Chart.csv has no days with any clicks or impressions.')
    return clicks, min(days), max(days)


def place(clicks, countries):
    by_name = {}
    for country in countries:
        for name in country['names']:
            by_name.setdefault(name, country['code'])
    by_code = {c['code']: c for c in countries}

    visits, shown, unknown = {}, {}, []
    for name, n in sorted(clicks.items(), key=lambda item: -item[1]):
        key = norm(re.sub(r'\(.*?\)', '', name))  # 'Myanmar (Burma)' -> 'myanmar'
        if n <= 0 or key in NOT_PLACES:
            continue
        code = NAME_FIXES.get(key) or by_name.get(key) or by_name.get(norm(name))
        if code not in by_code:
            unknown.append(name)
            continue
        visits[code] = visits.get(code, 0) + n
        shown.setdefault(code, SHOWN_AS.get(name, name))  # the name with the most visits
    if unknown:
        sys.exit('Not on the map yet (add them to NAME_FIXES in scripts/visitor-map/build.py):\n  '
                 + '\n  '.join(sorted(unknown)))
    return visits, shown


def fmt(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def dots_path(dots):
    """Each unbroken stretch of a row is one short line, dashed into round dots one unit apart."""
    return ''.join(f'M{fmt(dot_x(row, col) - 0.5)} {row}h{n}' for row, col, n in to_runs(dots))


def nice_date(day):
    d = datetime.date.fromisoformat(day)
    return f'{d:%b} {d.day}, {d.year}'


def overlaps(a, b):
    return a[0] < b[2] and b[0] < a[2] and a[1] < b[3] and b[1] < a[3]


def place_labels(spots, ranked, shown):
    """Name the top countries next to their bubbles: on the right if there's room, else
    below, left or above, clear of other bubbles and of the labels placed so far."""
    taken = {code: (x - r, y - r, x + r, y + r) for code, (x, y, r) in spots.items() if r >= 1.2}
    placed, labels = [], []
    for code in ranked[:LABELS]:
        x, y, r = spots[code]
        w, h, gap = len(shown[code]) * LABEL_SIZE * 0.55, LABEL_SIZE * 1.1, 0.8
        sides = [(x + r + gap, y, 'start'), (x, y + r + h, 'middle'),
                 (x - r - gap, y, 'end'), (x, y - r - h, 'middle')]
        for lx, ly, anchor in sides + [sides[0]]:  # nowhere free: the right it is
            left = {'start': lx, 'middle': lx - w / 2, 'end': lx - w}[anchor]
            box = (left, ly - h / 2, left + w, ly + h / 2)
            others = placed + [b for other, b in taken.items() if other != code]
            if not any(overlaps(box, other) for other in others):
                break
        placed.append(box)
        labels.append(f'<text x="{fmt(lx)}" y="{fmt(ly)}" text-anchor="{anchor}">{html.escape(shown[code])}</text>')
    return ''.join(labels)


def render(land, visits, shown, first_day, last_day):
    countries = {c['code']: c for c in land['countries']}
    dots = from_runs(land['land'])
    ranked = sorted(visits, key=lambda code: (-visits[code], shown[code]))
    most = visits[ranked[0]]
    spots = {code: (*lonlat_to_xy(*countries[code]['label']),
                    max(BUBBLE_MIN, BUBBLE_MAX * math.sqrt(visits[code] / most)))
             for code in visits}
    x0 = min(dot_x(r, c) for r, c in dots) - 1.5
    x1 = max(dot_x(r, c) for r, c in dots) + 1.5
    y0 = min(r for r, _ in dots) - 1.5
    y1 = max(r for r, _ in dots) + 1.5

    # Biggest first, so smaller bubbles sit on top and stay easy to point at.
    bubbles = ''.join(f'<circle cx="{fmt(spots[c][0])}" cy="{fmt(spots[c][1])}" r="{fmt(spots[c][2])}" '
                      f'data-name="{html.escape(shown[c])}"/>' for c in ranked)
    pings = ''.join(f'<circle class="reach-ping" style="animation-delay:{i * 0.6:.1f}s" '
                    f'cx="{fmt(spots[c][0])}" cy="{fmt(spots[c][1])}" r="{fmt(spots[c][2])}"/>'
                    for i, c in enumerate(ranked[:PINGS]))
    labels = place_labels(spots, ranked, shown)

    continents = {countries[code]['continent'] for code in visits} - {'Seven seas (open ocean)', 'Antarctica'}
    chips = ''.join(f'<li>{html.escape(shown[code])}</li>' for code in ranked[:TOP_CHIPS])

    return f'''{START}
    <section class="reach" id="world">
        <div class="section-inner">
            <h2 class="section-title">Fun, free typing practice for kids everywhere. 🐾</h2>
            <p class="section-sub">Typists in <strong>{len(visits)} countries</strong> across <strong>{len(continents)} continents</strong> have found TypePets so far.</p>

            <figure class="reach-card">
                <div class="reach-map-wrap">
                    <svg class="reach-map" viewBox="{fmt(x0)} {fmt(y0)} {fmt(x1 - x0)} {fmt(y1 - y0)}" role="img"
                         aria-label="World map with a bubble on each of the {len(visits)} countries TypePets visitors come from, biggest for {', '.join(shown[c] for c in ranked[:3])}">
                        <path class="reach-land" d="{dots_path(dots)}"/>
                        <g class="reach-bubbles">{bubbles}</g>
                        <g class="reach-pings" aria-hidden="true">{pings}</g>
                        <g class="reach-labels" aria-hidden="true">{labels}</g>
                    </svg>
                    <div class="reach-legend" aria-hidden="true">
                        <span class="reach-label">Visitors</span>
                        <span class="reach-scale">Fewer <span class="reach-key reach-k1"></span><span class="reach-key reach-k2"></span><span class="reach-key reach-k3"></span> More</span>
                    </div>
                    <div class="reach-tip" aria-hidden="true" hidden></div>
                </div>
                <figcaption class="reach-foot">
                    <span class="reach-label">Most visits from</span>
                    <ul class="reach-chips">{chips}</ul>
                </figcaption>
            </figure>
            <p class="reach-note">Countries with at least one visit from Google Search, {nice_date(first_day)} to {nice_date(last_day)}.</p>
        </div>
    </section>
    {END}'''


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('export', nargs='?', help='Search Console export zip (or the folder it unzips to)')
    parser.add_argument('--check', action='store_true', help='exit 1 if index.html is out of date')
    parser.add_argument('--land', metavar='GEOJSON', help='rebuild land.json from Natural Earth countries')
    args = parser.parse_args()

    if args.land:
        build_land(args.land)
        if not args.export:
            return 0
    if not args.export:
        parser.error('pass the Search Console export zip')

    land = json.loads(LAND_FILE.read_text(encoding='utf-8'))
    if (land['cols'], land['rows']) != (COLS, ROWS):
        sys.exit('land.json was built for a different grid: rebuild it with --land.')
    clicks, first_day, last_day = read_export(args.export)
    visits, shown = place(clicks, land['countries'])
    block = render(land, visits, shown, first_day, last_day)

    page = INDEX.read_text(encoding='utf-8')
    start, end = page.find(START), page.find(END)
    if start < 0 or end < 0:
        sys.exit(f'index.html needs the two visitor-map marker lines:\n  {START}\n  {END}')
    new_page = page[:start] + block + page[end + len(END):]
    if args.check:
        if new_page != page:
            print('The visitor map in index.html is out of date. Run without --check.')
            return 1
        print('The visitor map is up to date.')
        return 0
    INDEX.write_text(new_page, encoding='utf-8')
    print(f'Visitor map: {len(visits)} countries, {nice_date(first_day)} to {nice_date(last_day)}.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
